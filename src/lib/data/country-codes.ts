/**
 * Daftar kode telepon negara (E.164 calling codes).
 *
 * Dipakai untuk pemilih kode negara pada semua form nomor telepon. Flag emoji
 * dibangkitkan dari kode ISO alpha-2 lewat regional indicator symbols, sehingga
 * tidak perlu menyimpan emoji secara manual.
 */

export interface CountryCode {
    /** Kode negara ISO 3166-1 alpha-2 (contoh: 'ID'). */
    iso: string
    /** Nama negara (Bahasa Indonesia). */
    name: string
    /** Kode panggil internasional tanpa tanda plus (contoh: '62'). */
    dial: string
}

/** Ubah ISO alpha-2 menjadi flag emoji (mis. 'ID' -> '🇮🇩'). */
export function isoToFlag(iso: string): string {
    const upper = iso.toUpperCase()
    if (upper.length !== 2) return ''
    return (
        String.fromCodePoint(0x1f1e6 + upper.charCodeAt(0) - 65) +
        String.fromCodePoint(0x1f1e6 + upper.charCodeAt(1) - 65)
    )
}

/** Kode negara Indonesia (default). */
export const DEFAULT_COUNTRY_CODE = '62'
export const DEFAULT_COUNTRY_ISO = 'ID'

/** Ambil kode panggil (dial) dari kode ISO, jatuh ke '62' bila tak dikenal. */
export function getDialByIso(iso: string): string {
    return COUNTRY_CODES.find((c) => c.iso === iso)?.dial ?? DEFAULT_COUNTRY_CODE
}

/** Ambil kode ISO dari kode panggil (dial), jatuh ke 'ID' bila tak dikenal. */
export function getIsoByDial(dial: string): string {
    return COUNTRY_CODES.find((c) => c.dial === dial)?.iso ?? DEFAULT_COUNTRY_ISO
}

/** Cek apakah kode ISO dikenal dalam daftar. */
export function isKnownIso(iso: string): boolean {
    return COUNTRY_CODES.some((c) => c.iso === iso)
}

